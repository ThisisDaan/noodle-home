"""One Noodle logo for everything. Edit the mark below, run `python brand/build.py`, and the web logo, favicon and
Android launcher icon are all written from it.

The mark: the letter N drawn as one continuous wire (a noodle) with a node at each end.
Coordinates are on a 32x32 canvas.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BG = "#605dff"      # tile background (the interface's primary colour)
WIRE = "#ffffff"
NODE = "#ffb347"

WIRE_PATH = "M9 23V9.8c0-1.4 1.7-2 2.5-.9l9 12.2c.8 1.1 2.5.5 2.5-.9V9"
NODES = [(9, 23.5), (23, 8.5)]
WIRE_WIDTH, NODE_R = 3.6, 3.1


def mark() -> str:
    nodes = "".join(f'<circle cx="{x}" cy="{y}" r="{NODE_R}"/>' for x, y in NODES)
    return (f'<path d="{WIRE_PATH}" stroke="{WIRE}" stroke-width="{WIRE_WIDTH}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<g fill="{NODE}">{nodes}</g>')


TILE = f'<rect width="32" height="32" rx="8" fill="{BG}"/>'

# Web: the logo component (the house takes the text colour) and the favicon (with its background).
(ROOT / "noodle/frontend/src/lib/Logo.svelte").write_text(f'''<script lang="ts">
	let {{ class: cls = 'size-6' }}: {{ class?: string }} = $props();
</script>

<!-- The Noodle logo, with its own tile so it looks the same on any background. Generated by brand/build.py. -->
<svg viewBox="0 0 32 32" fill="none" aria-hidden="true" class={{cls}}>{TILE}{mark()}</svg>
''', encoding="utf-8")

(ROOT / "noodle/frontend/static/favicon.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" fill="none"><rect width="32" height="32" rx="8" fill="{BG}"/>'
    f'{mark()}</svg>\n', encoding="utf-8")

# Android: adaptive icon. The mark is scaled into the middle 66dp of the 108dp canvas (the part every launcher shows).
S, T = 2.4, 54 - 16 * 2.4


def android_node(x: float, y: float) -> str:
    # A circle as a path, since vector drawables have no <circle>.
    r = NODE_R
    return (f'<path android:fillColor="{NODE}" android:pathData="M{x - r},{y}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0"/>')


res = ROOT / "noodle-android/app/src/main/res"
(res / "drawable/ic_foreground.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/build.py, do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{S}" android:scaleY="{S}" android:translateX="{T}" android:translateY="{T}">
        <path android:pathData="{WIRE_PATH}" android:strokeColor="{WIRE}" android:strokeWidth="{WIRE_WIDTH}"
            android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>
        {"".join(android_node(x, y) for x, y in NODES)}
    </group>
</vector>
''', encoding="utf-8")
(res / "values/colors.xml").write_text(f'''<resources>
    <color name="ic_background">{BG}</color>
</resources>
''', encoding="utf-8")
print("logo written")
